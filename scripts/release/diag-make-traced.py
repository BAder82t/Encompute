#!/usr/bin/env python3
"""Generate the instrumented (traced) copies of the two regression test files.

TEST-ONLY diagnostic. Each copy is the original file byte for byte except:
  * a `#[path]` module line that pulls in the passive tracer, and
  * the body of `fn in_window`, which delegates to the traced helper
    (same signature, plus `R: Debug`).
The originals are never edited. `--check` fails if a committed copy is stale.

usage: diag-make-traced.py [--check] [repo-root]
"""
import pathlib
import sys

PAIRS = ["anchor_window_adversarial", "anchor_negatives"]
MOD_LINE = "mod common;\n"
TRACE_MOD = (
    '\n#[path = "diag/trace_window.rs"]\n'
    "#[allow(dead_code)]\n"
    "mod trace_window;\n"
)
HEADER = (
    "// GENERATED by scripts/release/diag-make-traced.py from {name}.rs -- TEST-ONLY diagnostic.\n"
    "// Identical to the original except `in_window`, which delegates to the passively\n"
    "// instrumented helper in diag/trace_window.rs. Do not edit; regenerate.\n"
    "#![allow(unused_imports)]\n"
)
NEW_FN = (
    "fn in_window<R: Send + std::fmt::Debug>(\n"
    "    url: &str,\n"
    "    tables: &[&str],\n"
    "    attack_sql: &str,\n"
    "    acting: impl FnOnce() -> R + Send,\n"
    ") -> R {\n"
    "    trace_window::in_window_traced(url, tables, attack_sql, acting)\n"
    "}\n"
)


def transform(name: str, text: str) -> str:
    lines = text.splitlines(keepends=True)
    start = next(i for i, l in enumerate(lines) if l.startswith("fn in_window<R: Send>("))
    end = next(i for i in range(start, len(lines)) if lines[i] == "}\n")
    out = "".join(lines[:start]) + NEW_FN + "".join(lines[end + 1 :])
    if out.count(MOD_LINE) != 1:
        raise SystemExit(f"{name}: expected exactly one `mod common;`")
    out = out.replace(MOD_LINE, MOD_LINE + TRACE_MOD, 1)
    return HEADER.format(name=name) + out


def main() -> int:
    args = [a for a in sys.argv[1:] if a != "--check"]
    check = "--check" in sys.argv[1:]
    root = pathlib.Path(args[0] if args else ".")
    tests = root / "crates/encompute-control/tests"
    bad = 0
    for name in PAIRS:
        want = transform(name, (tests / f"{name}.rs").read_text())
        dst = tests / f"{name}_traced.rs"
        if check:
            if not dst.exists() or dst.read_text() != want:
                print(f"STALE: {dst}")
                bad = 1
        else:
            dst.write_text(want)
            print(f"wrote {dst}")
    return bad


if __name__ == "__main__":
    sys.exit(main())
